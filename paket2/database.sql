CREATE DATABASE IF NOT EXISTS klinikzakwan_paket1;
USE klinikzakwan_paket1;
CREATE TABLE pasien(id INT AUTO_INCREMENT PRIMARY KEY,nama VARCHAR(100) NOT NULL,umur INT NOT NULL,jenis_kelamin VARCHAR(20) NOT NULL,keluhan TEXT NOT NULL,tanggal_masuk DATE NOT NULL);
CREATE TABLE dokter(id INT AUTO_INCREMENT PRIMARY KEY,nama_dokter VARCHAR(100) NOT NULL,spesialis VARCHAR(100) NOT NULL,no_hp VARCHAR(25) NOT NULL);
